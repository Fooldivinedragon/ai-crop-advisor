@app.route("/api/predict", methods=["POST"])
def predict():
    data = request.get_json(silent=True) or request.form.to_dict()
    try:
        args = _parse(data)
    except ValueError as exc:
        return jsonify({"error": str(exc)}), 400

    try:
        result = pipeline.run(**args)
    except LocationError as exc:
        return jsonify({"error": str(exc)}), 400
    except WeatherError as exc:
        return jsonify({"error": str(exc)}), 502
    return jsonify(result)


@app.route("/api/explain", methods=["POST"])
def explain_result():
    data = request.get_json(silent=True) or {}
    if not isinstance(data.get("result"), dict):
        return jsonify({"error": "Get a recommendation first, then ask for an explanation"}), 400
    try:
        out = explain(data["result"], int(data.get("crop_index", 0)), data.get("language", "en"))
    except (KeyError, TypeError, ValueError):
        return jsonify({"error": "Send the prediction result, crop_index and language"}), 400
    except ExplainRequestError as exc:
        return jsonify({"error": str(exc)}), 400
    except ExplainError as exc:
        return jsonify({"error": str(exc)}), 503
    return jsonify({"explanation": out["text"], "provider": out["provider"], "offline": out["offline"]})


if __name__ == "__main__":
    app.run(debug=True)
