app = Flask(__name__)


def _parse(data: dict) -> dict:
    def num(key, lo, hi, required=True):
        raw = data.get(key)
        if raw in (None, ""):
            if required:
                raise ValueError(f"{key} is required")
            return None
        value = float(raw)
        if not lo <= value <= hi:
            raise ValueError(f"{key} must be between {lo} and {hi}")
        return value

    raw_date = data.get("planting_date")
    if not raw_date:
        raise ValueError("planting_date is required")

    return {
        "N": num("N", 0, 300),
        "P": num("P", 0, 300),
        "K": num("K", 0, 300),
        "ph": num("ph", 0, 14),
        "planting_date": date.fromisoformat(raw_date),
        "district": (data.get("district") or "").strip() or None,
        "lat": num("lat", -90, 90, required=False),
        "lon": num("lon", -180, 180, required=False),
        "irrigated": str(data.get("irrigated", "true")).lower() in ("true", "1", "on", "yes"),
    }


with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "evaluation.json")) as f:
    EVALUATION = json.load(f)


